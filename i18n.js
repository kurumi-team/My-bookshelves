const LANG_STORAGE_KEY = 'mybookshelf_lang';
const SUPPORTED_LANGS = ['ja', 'en', 'vi'];

function getLang() {
  const stored = localStorage.getItem(LANG_STORAGE_KEY);
  return SUPPORTED_LANGS.includes(stored) ? stored : 'ja';
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
}

function t(key) {
  const lang = getLang();
  const table = UI_TEXT[lang] || UI_TEXT.ja;
  return table[key] !== undefined ? table[key] : (UI_TEXT.ja[key] || key);
}

function getTree() {
  return IMPRESSION_TREE_ALL[getLang()] || IMPRESSION_TREE_ALL.ja;
}

function formatCount(n) {
  const lang = getLang();
  if (lang === 'en') return `${n} book${n === 1 ? '' : 's'}`;
  if (lang === 'vi') return `${n} cuốn`;
  return `${n}冊`;
}

function formatDate(isoString) {
  const d = new Date(isoString);
  const lang = getLang();
  const locale = lang === 'en' ? 'en-US' : lang === 'vi' ? 'vi-VN' : 'ja-JP';
  try {
    return new Intl.DateTimeFormat(locale, { year: 'numeric', month: 'numeric', day: 'numeric' }).format(d);
  } catch {
    return `${d.getFullYear()}/${d.getMonth() + 1}/${d.getDate()}`;
  }
}

